# Writes src/editor/hw_i18n.gen.h from tools/i18n_ru.py (non-ASCII as octal escapes: the compiler's
# source code page does not matter).
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from i18n_ru import RU  # noqa: E402


def c_str(s):
    out = '"'
    for b in s.encode('utf-8'):
        c = chr(b)
        if c == '"':
            out += '\\"'
        elif c == '\\':
            out += '\\\\'
        elif c == '\n':
            out += '\\n'
        elif 32 <= b < 127:
            out += c
        else:
            out += '\\%03o' % b
    return out + '"'


lines = ['// Generated by tools/gen_i18n.py from tools/i18n_ru.py - do not edit.', '#pragma once', '',
         'static const char *const HW_I18N_RU[][2] = {']
for k in sorted(RU):
    lines.append('\t{ %s, %s },' % (c_str(k), c_str(RU[k])))
lines += ['};', '']
out = os.path.join(here, '..', 'src', 'editor', 'hw_i18n.gen.h')
open(out, 'w', encoding='ascii', newline='\n').write('\n'.join(lines))
print('wrote', out, len(RU), 'strings')

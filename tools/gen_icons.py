# Embeds the SVG icons of src/editor/icons into src/editor/hw_icons.gen.h.
# Icons: Tabler Icons (https://tabler.io/icons), MIT license, see src/editor/icons/LICENSE_TABLER.txt.
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'src', 'editor', 'icons')
out = os.path.join(here, '..', 'src', 'editor', 'hw_icons.gen.h')
BS = chr(92)
lines = ['// Generated by tools/gen_icons.py from src/editor/icons (Tabler Icons, MIT license). Do not edit.',
         '#pragma once', '', 'namespace hw_icons {', '', 'struct Icon {', '\tconst char *name;', '\tconst char *svg;', '};', '',
         'static const Icon ICONS[] = {']
for f in sorted(os.listdir(src)):
    if not f.endswith('.svg'):
        continue
    svg = open(os.path.join(src, f), encoding='utf-8').read()
    svg = ' '.join(svg.split()).replace(BS, BS + BS).replace('"', BS + '"')
    lines.append('\t{ "%s", "%s" },' % (f[:-4], svg))
lines += ['};', '', '} // namespace hw_icons', '']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('wrote', out)
